
"""IntelliTerminal: a safety-first terminal assistant for Windows learners."""

import argparse
import json
import os
import platform
import shutil
import subprocess
import sys
import urllib.error
import urllib.request

from intelliterminal.catalog import (
    BUNDLES,
    COMMANDS,
    find_command,
    match_request,
)
from intelliterminal.safety import (
    classify_risk,
    folder_name_error,
    is_allowed_to_run,
)


def ai_suggest(request):
    """Ask an optional local Ollama model for a suggestion."""
    if os.getenv("INTELLITERMINAL_AI", "").lower() != "ollama":
        return None

    url = os.getenv(
        "OLLAMA_URL", "http://localhost:11434"
    ).rstrip("/")
    model = os.getenv("OLLAMA_MODEL", "llama3.2:3b")

    prompt = (
        "You are a cautious terminal-command tutor. Suggest a "
        "command for the request. Explain OS compatibility and "
        "risk. Never execute commands. Warn about destructive "
        "commands. If unclear, ask a question. User request: "
        + request
    )

    payload = json.dumps({
        "model": model,
        "prompt": prompt,
        "stream": False,
    }).encode("utf-8")

    req = urllib.request.Request(
        f"{url}/api/generate",
        data=payload,
        headers={"Content-Type": "application/json"},
        method="POST",
    )

    try:
        with urllib.request.urlopen(req, timeout=35) as response:
            data = json.loads(response.read().decode("utf-8"))
        return data.get("response", "").strip() or None

    except (OSError, ValueError, urllib.error.URLError) as exc:
        print("Local AI unavailable:", exc)
        return None


def create_custom_folder():
    """Ask for the user's folder name and create it safely."""

    try:
        folder_name = input(
            "\nEnter your folder name "
            "(example: notes, College Project): "
        ).strip()

    except (EOFError, KeyboardInterrupt):
        print("\nCancelled. No folder was created.")
        return 0

    # Validate the name before displaying or creating anything.
    error = folder_name_error(folder_name)

    if error:
        print("Invalid folder name:", error)
        return 2

    # Put quotes around names containing spaces.
    if any(char.isspace() for char in folder_name):
        command_text = f'mkdir "{folder_name}"'
    else:
        command_text = f"mkdir {folder_name}"

    print("\nSuggested Windows command:", command_text)
    print("Type the command exactly as shown to create the folder.")
    print("Press Enter without typing anything to cancel.")

    try:
        typed_command = input("> ").strip()

    except (EOFError, KeyboardInterrupt):
        print("\nCancelled. No folder was created.")
        return 0

    # Only accept the exact command generated by the program.
    if typed_command.casefold() != command_text.casefold():
        print("Cancelled. The folder was not created.")
        return 0

    print("\nRunning approved command:", command_text)
    print("Safety review:", classify_risk(command_text))

    # Use Python's filesystem API instead of executing raw user text.
    try:
        os.mkdir(folder_name)

        print(f'\nFolder created successfully: "{folder_name}"')
        print("Location:", os.path.abspath(folder_name))
        return 0

    except FileExistsError:
        print(
            f'A file or folder named "{folder_name}" '
            "already exists here."
        )
        return 1

    except OSError as exc:
        print("Could not create the folder:", exc)
        return 1


def run_suggested_item(item):
    """Handle a matched command suggestion."""

    # Folder creation uses a name entered by the user.
    if item.get("id") == "mkdir":
        return create_custom_folder()

    command_text = item.get("windows", "")
    argv = item.get("windows_argv")

    # Some commands are suggestions only, not executable.
    if (
        not item.get("runnable")
        or not argv
        or not is_allowed_to_run(item)
    ):
        print(
            "\nThis command is shown for learning, but execution "
            "is disabled for safety. Review it and run it manually "
            "if appropriate."
        )
        return 0

    print("\nType the command exactly as shown below to run it.")
    print("Press Enter without typing anything to cancel.")

    try:
        typed_command = input(f"{command_text} > ").strip()

    except (EOFError, KeyboardInterrupt):
        print("\nCancelled. The command was not executed.")
        return 0

    if typed_command.casefold() != command_text.casefold():
        print("Cancelled. The command was not executed.")
        return 0

    print(f"\nRunning approved command: {command_text}")
    print("Safety review:", classify_risk(command_text))

    try:
        result = subprocess.run(
            argv,
            check=False,
            shell=False,
        )

        if result.returncode == 0:
            print("\nCommand completed successfully.")
        else:
            print(f"\nCommand exited with code {result.returncode}.")

        return result.returncode

    except (FileNotFoundError, OSError, subprocess.SubprocessError) as exc:
        print("Command execution failed:", exc)
        return 1


def suggest(request, use_ai=True):
    """Suggest a command from English or supported Hinglish."""

    item = match_request(request)

    if item:
        print("\nTask:", item["title"])
        print("Linux/macOS:", item["linux"])
        print("Windows:", item["windows"])
        print("Explanation:", item["explanation"])
        print("Risk:", item["risk"].upper())

        return run_suggested_item(item)

    # Try the optional local AI if no built-in phrase matches.
    answer = ai_suggest(request) if use_ai else None

    if answer:
        print("\nLOCAL AI SUGGESTION — REVIEW BEFORE USE\n")
        print(answer)
        print("AI output was not executed.")
        print("Review AI-generated commands before running them.")
        return 0

    print(
        "No confident match. Try 'folder banao', "
        "'files dikhao', 'git status', or 'last 5 commits'."
    )
    return 1


def run_bundle(name):
    """Run a predefined bundle of read-only diagnostic commands."""

    spec = BUNDLES.get(name)

    if not spec:
        print(f"Unknown bundle: {name}")
        return 2

    print("\n==", spec["title"], "==")
    overall = 0

    for section in spec["commands"]:
        print("\n--", section["title"], "--")
        command = section.get("command", [])

        if not command:
            print("Skipped: no command configured.")
            overall = 1
            continue

        if not shutil.which(command[0]):
            print("Skipped: executable not found:", command[0])

            if section.get("tip"):
                print("Tip:", section["tip"])

            overall = 1
            continue

        try:
            result = subprocess.run(
                command,
                capture_output=True,
                text=True,
                check=False,
                shell=False,
            )

            if result.stdout.strip():
                print(result.stdout.rstrip())

            if result.stderr.strip():
                print(result.stderr.rstrip(), file=sys.stderr)

            if result.returncode:
                overall = result.returncode

                if section.get("tip"):
                    print("Tip:", section["tip"])

        except (OSError, subprocess.SubprocessError) as exc:
            print("Command execution failed:", exc)
            overall = 1

    return overall


def explain(command):
    """Explain a command from the built-in catalog."""

    item = find_command(command)

    if not item:
        print(
            "Command not in the built-in explanation library. "
            "Run: python main.py commands"
        )
        return 1

    print(item["title"] + ": " + item["explanation"])
    print("Linux/macOS:", item["linux"])
    print("Windows:", item["windows"])
    print("Risk:", item["risk"].upper())

    return 0


def run_approved(command):
    """Run an exact allowlisted command after confirmation."""

    item = find_command(command)

    if (
        not item
        or not is_allowed_to_run(item)
        or not item.get("windows_argv")
    ):
        print("Blocked: command is not in the safe runnable allowlist.")
        return 2

    print("Command:", item["windows"])
    print("Explanation:", item["explanation"])
    print("Risk review:", classify_risk(item["windows"]))

    try:
        confirmation = input(
            "Type YES to run this approved command: "
        ).strip()

    except (EOFError, KeyboardInterrupt):
        print("\nCancelled. Nothing was executed.")
        return 0

    if confirmation != "YES":
        print("Cancelled. Nothing was executed.")
        return 0

    try:
        return subprocess.run(
            item["windows_argv"],
            check=False,
            shell=False,
        ).returncode

    except (OSError, subprocess.SubprocessError) as exc:
        print("Command execution failed:", exc)
        return 1


def show_commands():
    """Display all supported command mappings."""

    print("\n=== IntelliTerminal Command Library ===")

    for item in COMMANDS:
        print(f"\nTask: {item['title']}")

        if item.get("examples"):
            print("Example request:", item["examples"][0])

        print("Linux/macOS:", item["linux"])
        print("Windows:", item["windows"])
        print("Risk:", item["risk"].upper())


def doctor():
    """Print environment and optional AI configuration."""

    print("\n=== IntelliTerminal Environment ===")
    print("Operating system:", platform.platform())
    print("Python version:", sys.version.split()[0])
    print("Current directory:", os.getcwd())
    print("Git executable:", shutil.which("git") or "Not found")

    ai_mode = (
        "Ollama enabled"
        if os.getenv("INTELLITERMINAL_AI", "").lower() == "ollama"
        else "Offline command matching"
    )

    print("AI mode:", ai_mode)


def build_parser():
    parser = argparse.ArgumentParser(
        description=(
            "IntelliTerminal: natural-language "
            "terminal command helper"
        )
    )

    subparsers = parser.add_subparsers(
        dest="action",
        required=True,
    )

    suggest_parser = subparsers.add_parser(
        "suggest",
        help="Suggest a command from plain language",
    )
    suggest_parser.add_argument(
        "request",
        nargs="+",
        help="Your request",
    )
    suggest_parser.add_argument(
        "--no-ai",
        action="store_true",
        help="Disable optional local AI",
    )

    bundle_parser = subparsers.add_parser(
        "bundle",
        help="Combine related diagnostic commands",
    )
    bundle_parser.add_argument(
        "name",
        choices=sorted(BUNDLES.keys()),
    )

    explain_parser = subparsers.add_parser(
        "explain",
        help="Explain a known command",
    )
    explain_parser.add_argument(
        "command",
        nargs="+",
    )

    run_parser = subparsers.add_parser(
        "run",
        help="Run an allowlisted command after confirmation",
    )
    run_parser.add_argument(
        "command",
        nargs="+",
    )

    subparsers.add_parser(
        "commands",
        help="List supported command mappings",
    )
    subparsers.add_parser(
        "doctor",
        help="Check the environment",
    )

    return parser


def main(argv=None):
    args = build_parser().parse_args(argv)

    if args.action == "suggest":
        return suggest(
            " ".join(args.request),
            use_ai=not args.no_ai,
        )

    if args.action == "bundle":
        return run_bundle(args.name)

    if args.action == "explain":
        return explain(" ".join(args.command))

    if args.action == "run":
        return run_approved(" ".join(args.command))

    if args.action == "commands":
        show_commands()
        return 0

    if args.action == "doctor":
        doctor()
        return 0

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
